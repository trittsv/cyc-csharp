static void shape_args(FILE *f, const shape *s) {
  for (size_t i = 0; i < s->rank; i++) fprintf(f, "%s%"PRIu32, i ? ", " : "", s->dims[i]);
}

static void type_name(FILE *f, const void *type, const idl_declarator_t *decl) {
  shape s;
  if (!get_shape(&s, type, decl)) return;
  const char *base = primitive(s.base, false);
  if (base) fputs(base, f);
  else if (idl_is_string(s.base)) fputs("string", f);
  else if (idl_is_sequence(s.base)) {
    fputs("global::Omg.Types.ISequence<", f);
    type_name(f, idl_type_spec(s.base), NULL);
    fputc('>', f);
  } else scoped(f, s.base, true);
  if (s.rank) {
    fputc('[', f);
    for (size_t i = 1; i < s.rank; i++) fputc(',', f);
    fputc(']', f);
  }
}

